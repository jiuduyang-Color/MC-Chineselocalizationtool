    public static string T(string key, params object[] args)
    {
        var dict = _lang == UILanguage.Chinese ? _zh : _en;
        if (!dict.TryGetValue(key, out var val))
            return _en.TryGetValue(key, out var fallback) ? (args.Length > 0 ? string.Format(fallback, args) : fallback) : key;
        return args.Length > 0 ? string.Format(val, args) : val;
    }
